#!/usr/bin/env bash
# Write /opt/nginx/conf/nginx.conf for one of two TLS profiles.
#
#   classical : ssl_ecdh_curve X25519:prime256v1                 (what arm A can do)
#   pq        : ssl_ecdh_curve X25519MLKEM768:X25519:prime256v1  (needs arm B)
#
# Same ECDSA P-256 cert in both — this phase is about the KEM-first migration, which is
# what production can actually ship today (browsers don't trust ML-DSA certs yet).
#
# Session cache and tickets are OFF so every connection is a full handshake: we are
# measuring the cost of the handshake path, not resumption.
#
# The access log records which worker PID served each request ($pid) and the negotiated
# group ($ssl_curve), so a reload or binary swap is visible request-by-request.
#
# Usage: sudo ./make-conf.sh classical|pq
set -euo pipefail
PROFILE=${1:?usage: make-conf.sh classical|pq}
PREFIX=/opt/nginx
CERTDIR=$PREFIX/conf/certs

case "$PROFILE" in
  classical) CURVES="X25519:prime256v1" ;;
  pq)        CURVES="X25519MLKEM768:X25519:prime256v1" ;;
  *) echo "unknown profile $PROFILE"; exit 1 ;;
esac

if [ ! -f "$CERTDIR/ecdsa.crt" ]; then
  mkdir -p "$CERTDIR"
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes \
    -keyout "$CERTDIR/ecdsa.key" -out "$CERTDIR/ecdsa.crt" \
    -subj "/CN=pqc-bench-phase7" -days 30 2>/dev/null
fi

cat > "$PREFIX/conf/nginx.conf" <<EOF
# generated by make-conf.sh — profile: $PROFILE
worker_processes auto;
worker_rlimit_nofile 65536;
pid $PREFIX/logs/nginx.pid;
error_log $PREFIX/logs/error.log notice;

events {
    worker_connections 16384;
}

http {
    log_format bench '\$msec \$pid \$connection \$ssl_protocol \$ssl_curve \$status \$request_time';
    access_log $PREFIX/logs/bench.log bench buffer=256k flush=1s;

    server {
        listen 443 ssl reuseport backlog=16384;
        server_name _;

        ssl_certificate     $CERTDIR/ecdsa.crt;
        ssl_certificate_key $CERTDIR/ecdsa.key;
        ssl_protocols       TLSv1.3;
        ssl_ecdh_curve      $CURVES;
        ssl_session_cache   off;
        ssl_session_tickets off;

        location / {
            add_header X-Worker-Pid \$pid always;
            return 200 "ok\n";
        }
    }
}
EOF
echo "wrote $PREFIX/conf/nginx.conf (profile=$PROFILE, curves=$CURVES)"
